import { afterEach, expect, it } from 'vitest';
import { existsSync } from 'node:fs';
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { promisify } from 'node:util';

/**
 * Integration: the ARM64 family manifest written by the real runtime producer's
 * `writeFamilyManifest` is accepted by this launcher's production verifier.
 *
 * The payload here is inert (synthetic text files); nothing is built, executed
 * or downloaded, and this is not native ARM64 or game evidence. It closes the
 * gap between hand-authored fixtures and the actual producer schema: the manifest
 * is generated by `nexus/family-manifest.mjs` from the sibling read-only
 * checkout, then parsed by `verifyRuntimeFamilyPayload`.
 *
 * The producer checkout is a sibling of this repository only in the local
 * combined checkout. Where it is absent the test reports an explicit SKIP through
 * vitest's own skip mechanism, so an absent producer is never counted as a pass.
 */
// Sibling sources: <task>/source/nexus-launcher/src/main -> <task>/source/nexus-runtime.
const producer = path.resolve(__dirname, '../../../nexus-runtime/nexus/family-manifest.mjs');
const execute = promisify(execFile);
const roots: string[] = [];
afterEach(async () => { for (const root of roots.splice(0)) await fs.rm(root, { recursive: true, force: true }); });

it.skipIf(!existsSync(producer))('accepts the producer-generated ARM64 Standard manifest through the production verifier', async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'producer-arm64-'));
  roots.push(root);
  const commit = 'a'.repeat(40), lock = 'b'.repeat(64);
  const names = ['proton', 'files/bin-arm64/wine', 'files/bin-arm64/wineserver', 'files/bin-arm64/wine.nexus-original',
    ...['PlayFabGameSave.dll', 'gaming-services-version.exe', 'package-registration.exe'].map(name => 'files/share/xodus-nexus/compat/' + name),
    ...['aarch64', 'x86_64', 'i386'].flatMap(cpu => ['xgameruntime.dll', 'winhttp.dll', 'libnghttp2.dll'].map(name => `files/lib/wine/${cpu}-windows/${name}`))];
  // Inert aarch64 ELF identification block (no code) for the three loader entry
  // points the ARM64 contract inspects; every other file is synthetic text.
  const arm64Header = Buffer.alloc(64);
  arm64Header[0] = 0x7f; arm64Header[1] = 0x45; arm64Header[2] = 0x4c; arm64Header[3] = 0x46;
  arm64Header[4] = 2; arm64Header[5] = 1; arm64Header[6] = 1; arm64Header.writeUInt16LE(183, 18);
  const loader = /\/bin-arm64\/(wine|wineserver|wine\.nexus-original)$/;
  for (const name of names) {
    const file = path.join(root, name);
    await fs.mkdir(path.dirname(file), { recursive: true });
    await fs.writeFile(file, loader.test(name) ? arm64Header : 'inert producer fixture ' + name, { mode: 0o755 });
  }
  await fs.mkdir(path.join(root, 'files/share/default_pfx_arm64/dosdevices'), { recursive: true });
  await fs.symlink('/', path.join(root, 'files/share/default_pfx_arm64/dosdevices/z:'));
  await fs.writeFile(path.join(root, 'XODUS_NEXUS_PATCH.json'), JSON.stringify({
    schema: 1, sourceGraph: { proton: commit }, sourceLockSha256: lock,
    targetArchitecture: 'arm64', binDirectory: 'bin-arm64', defaultPrefix: 'default_pfx_arm64',
    componentsByArch: { 'aarch64-windows': {} },
  }));
  const script = [
    `const { writeFamilyManifest } = await import(${JSON.stringify(producer)});`,
    `const receipt = await writeFamilyManifest(${JSON.stringify(root)}, { family: 'nexus', sourceCommit: ${JSON.stringify(commit)}, sourceLockSha256: ${JSON.stringify(lock)}, arch: 'arm64' });`,
    'console.log(JSON.stringify(receipt));',
  ].join('\n');
  const { stdout } = await execute(process.execPath, ['--input-type=module', '-e', script], { timeout: 60000 });
  const receipt = JSON.parse(stdout.trim().split('\n').at(-1)!);
  expect(receipt).toMatchObject({ family: 'nexus', arch: 'arm64' });
  const bytes = await fs.readFile(path.join(root, 'nexus-family.json')), manifest = JSON.parse(bytes.toString('utf8'));
  expect(manifest).toMatchObject({ schema: 1, family: 'nexus', arch: 'arm64', prefixSchema: 1, buildId: receipt.buildId });
  expect(manifest.symlinks['files/share/default_pfx_arm64/dosdevices/z:']).toBe('/');
  const { verifyRuntimeFamilyPayload } = await import('./runtime-families');
  const pointer = { schema: 1 as const, family: 'nexus', sourceRepository: manifest.sourceRepository, sourceCommit: manifest.sourceCommit,
    manifestSha256: createHash('sha256').update(bytes).digest('hex'), buildId: manifest.buildId };
  const value = await verifyRuntimeFamilyPayload(root, pointer, 'arm64');
  expect(value.arch).toBe('arm64');
  expect(value.winePath).toBe(path.join(value.root, 'files/bin-arm64/wine'));
  // The same producer payload is not an x64 payload and no second family adopts it.
  await expect(verifyRuntimeFamilyPayload(root, pointer, 'x64')).rejects.toThrow();
});
